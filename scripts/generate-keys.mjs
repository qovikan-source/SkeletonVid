import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");

export async function generateKeys() {
  console.log("[SkeletonVid] Generating deterministic RSA-2048 keypair for Chrome Extension...");
  
  // 1. RSA-2048 Keypair for Chrome MV3 Extension ID
  const { publicKey: rsaPub, privateKey: rsaPriv } = crypto.generateKeyPairSync("rsa", {
    modulusLength: 2048,
    publicKeyEncoding: { type: "spki", format: "der" },
    privateKeyEncoding: { type: "pkcs8", format: "pem" }
  });

  // Base64 public key for manifest.json "key"
  const rsaPubB64 = rsaPub.toString("base64");

  // Derive Chrome Extension ID:
  // SHA-256 of the DER-encoded SubjectPublicKeyInfo, first 16 bytes encoded as [a-p]
  const sha256 = crypto.createHash("sha256").update(rsaPub).digest();
  let extensionId = "";
  for (let i = 0; i < 16; i++) {
    const byte = sha256[i];
    extensionId += String.fromCharCode(97 + (byte >> 4));
    extensionId += String.fromCharCode(97 + (byte & 0x0f));
  }

  console.log(`[SkeletonVid] Derived Chrome Extension ID: ${extensionId}`);

  // 2. Ed25519 Keypair for Licensing (Cloudflare Worker -> Go Native Host)
  console.log("[SkeletonVid] Generating Ed25519 keypair for double-gate licensing...");
  const subtle = crypto.webcrypto.subtle;
  const edKeyPair = await subtle.generateKey({ name: "Ed25519" }, true, ["sign", "verify"]);
  const privateJwk = await subtle.exportKey("jwk", edKeyPair.privateKey);
  const publicRaw = await subtle.exportKey("raw", edKeyPair.publicKey);
  const ed25519PubB64 = Buffer.from(publicRaw).toString("base64");

  return {
    rsaPubB64,
    rsaPrivPem: rsaPriv,
    extensionId,
    ed25519PubB64,
    ed25519PrivateJwk: JSON.stringify(privateJwk)
  };
}

export async function applyKeys() {
  const keys = await generateKeys();

  // 1. Write or update extension/manifest.json
  const manifestPath = path.join(rootDir, "extension", "manifest.json");
  if (fs.existsSync(manifestPath)) {
    const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf-8"));
    manifest.key = keys.rsaPubB64;
    fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n", "utf-8");
    console.log(`[SkeletonVid] Updated ${manifestPath} with static key.`);
  }

  // 2. Write or update native-host/config.go
  const hostConfigPath = path.join(rootDir, "native-host", "config.go");
  const hostConfigContent = `package main

// Code generated by scripts/generate-keys.mjs; DO NOT EDIT.

const (
	HostName         = "com.SkeletonVid.host"
	ExtensionID      = "${keys.extensionId}"
	Ed25519PubKeyB64 = "${keys.ed25519PubB64}"
)
`;
  fs.mkdirSync(path.dirname(hostConfigPath), { recursive: true });
  fs.writeFileSync(hostConfigPath, hostConfigContent, "utf-8");
  console.log(`[SkeletonVid] Updated ${hostConfigPath} with ExtensionID & Ed25519 key.`);

  // 3. Write backend/.dev.vars and backend/test-token.json
  const backendDir = path.join(rootDir, "backend");
  fs.mkdirSync(backendDir, { recursive: true });
  const devVarsPath = path.join(backendDir, ".dev.vars");
  const devVarsContent = `# Cloudflare Worker Local Secrets
STRIPE_SECRET_KEY=sk_test_placeholder_for_local_testing
STRIPE_WEBHOOK_SECRET=whsec_placeholder
STRIPE_PRICE_ID=price_test_placeholder
ED25519_PRIVATE_KEY_JWK='${keys.ed25519PrivateJwk}'
`;
  fs.writeFileSync(devVarsPath, devVarsContent, "utf-8");
  console.log(`[SkeletonVid] Updated ${devVarsPath}`);

  // 4. Save key backup in .keys/ for developer reference
  const keysBackupDir = path.join(rootDir, ".keys");
  fs.mkdirSync(keysBackupDir, { recursive: true });
  fs.writeFileSync(path.join(keysBackupDir, "extension-id.txt"), keys.extensionId + "\n");
  fs.writeFileSync(path.join(keysBackupDir, "extension-public-key.b64"), keys.rsaPubB64 + "\n");
  fs.writeFileSync(path.join(keysBackupDir, "extension-private-key.pem"), keys.rsaPrivPem + "\n");
  fs.writeFileSync(path.join(keysBackupDir, "ed25519-public-key.b64"), keys.ed25519PubB64 + "\n");
  fs.writeFileSync(path.join(keysBackupDir, "ed25519-private.jwk.json"), keys.ed25519PrivateJwk + "\n");

  console.log("[SkeletonVid] Key generation & synchronization complete!");
  return keys;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  applyKeys().catch((err) => {
    console.error("[SkeletonVid] Key generation failed:", err);
    process.exit(1);
  });
}
